export function dashboardText(language: InterfaceLanguage, english: string, filipino?: string) {
  const translated = filipino ?? FILIPINO_TRANSLATIONS[english] ?? english;
  if (language === "fil") return translated;
  if (language === "both" && translated !== english) return `${english} / ${translated}`;
  return english;
}

export function useDashboardText() {
  const { language } = useInterfaceLanguage();
  return useCallback((english: string, filipino?: string) => dashboardText(language, english, filipino), [language]);
}
